"""Dyna-Q learner: Q, reward and death heads on frozen world-model features, trained on real and imagined transitions.

Real transitions come from the actors' episode files (RL/real), imagined ones from imagine.py (RL/imag: f(s), a, f(s')
where s' was generated by the world model). Both live in GPU replay buffers.
  real:      y = 10 * delta log length + gamma * (1 - done) * Q_targ(s', argmax_a' Q(s', a'))     (double DQN)
  imagined:  y = R(s, a) + gamma * (1 - sigmoid D(s, a)) * Q_targ(s', argmax Q(s', .))           (model reward + death)
R and D are fitted on real transitions only. Target net = EMA of the heads. Replay ratio is capped so each transition is
used ~K times. Writes RL/heads.pt (for the actors) and RL/dash/learner.jsonl; backs up to the HF bucket under rl/.
"""
import argparse, glob, json, os, sys, time, copy
import numpy as np, torch, torch.nn.functional as F
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
import rlcore as R

OUT = R.RL
for d in ("real", "imag", "dash"): os.makedirs(f"{OUT}/{d}", exist_ok=True)


class Buf:
    def __init__(s, cap, d=1024, dev="cuda"):
        s.cap, s.n, s.i, s.total = cap, 0, 0, 0
        s.f = torch.zeros(cap, d, dtype=torch.float16, device=dev); s.f2 = torch.zeros_like(s.f)
        s.a = torch.zeros(cap, dtype=torch.long, device=dev); s.r = torch.zeros(cap, device=dev); s.d = torch.zeros(cap, device=dev)
    def add(s, f, a, f2, r=None, d=None):
        k = len(a)
        if k == 0: return
        idx = (torch.arange(k, device=s.f.device) + s.i) % s.cap
        s.f[idx] = f.to(s.f); s.f2[idx] = f2.to(s.f); s.a[idx] = a
        if r is not None: s.r[idx] = r; s.d[idx] = d
        s.i = (s.i + k) % s.cap; s.n = min(s.cap, s.n + k); s.total += k
    def sample(s, b):
        j = torch.randint(0, s.n, (b,), device=s.f.device)
        return s.f[j].float(), s.a[j], s.f2[j].float(), s.r[j], s.d[j]


def ingest_real(buf, seen, stats):
    new = sorted(set(glob.glob(f"{OUT}/real/ep_*.npz")) - seen)
    for p in new:
        seen.add(p)
        try: z = np.load(p)
        except Exception: continue
        f, a, r, d = z["f"], z["a"], z["r"], z["done"]; n = len(a)
        if n < 1: continue
        keep = list(range(n - 1)) + ([n - 1] if d[-1] else [])        # last decision only if terminal (else no s')
        f2 = np.concatenate([f[1:], np.zeros_like(f[:1])])
        k = np.array(keep)
        if len(k) == 0: continue
        buf.add(torch.from_numpy(f[k]).cuda(), torch.from_numpy(a[k].astype(np.int64)).cuda(), torch.from_numpy(f2[k]).cuda(),
                torch.from_numpy(r[k] * R.REWARD_SCALE).float().cuda(), torch.from_numpy(d[k].astype(np.float32)).cuda())
        stats["real_eps"] += 1; stats["deaths"] += int(d[-1])
    return len(new)


def ingest_imag(buf, stats):
    for p in sorted(glob.glob(f"{OUT}/imag/im_*.npz")):
        try: z = np.load(p)
        except Exception: continue
        buf.add(torch.from_numpy(z["f"]).cuda(), torch.from_numpy(z["a"].astype(np.int64)).cuda(), torch.from_numpy(z["f2"]).cuda())
        os.remove(p)                                   # pipeline scratch: consumed into the GPU buffer


def main(a):
    torch.manual_seed(0)
    H = R.Heads().cuda(); Tg = copy.deepcopy(H).requires_grad_(False)
    opt = torch.optim.AdamW(H.parameters(), lr=a.lr, weight_decay=1e-4)
    real, imag = Buf(a.cap), Buf(a.cap)
    seen, stats = set(), dict(real_eps=0, deaths=0)
    step, ver, t_save, t_log, t_hf = 0, 0, 0.0, 0.0, time.time()
    if os.path.exists(f"{OUT}/learner_state.pt"):                     # resume after a restart
        ck = torch.load(f"{OUT}/learner_state.pt", map_location="cuda")
        H.load_state_dict(ck["heads"]); Tg.load_state_dict(ck["targ"]); opt.load_state_dict(ck["opt"]); step, ver = ck["step"], ck["ver"]
        print(f"resumed at step {step}", flush=True)
    acc = dict(lq=0., lqr=0., lqi=0., lr_=0., ld=0., q=0., n=0, pd_dead=0., pd_alive=0., nd=0)
    t0 = time.time(); last_ing = 0.0
    while True:
        if time.time() - last_ing > 5:
            ingest_real(real, seen, stats); ingest_imag(imag, stats); last_ing = time.time()
        budget = a.replay_ratio * (real.total + imag.total) / (a.bs * 2) - step
        if real.n < a.warmup or budget < 1:
            time.sleep(0.5)
        else:
            fr, ar, f2r, rr, dr = real.sample(a.bs)
            with torch.no_grad():
                tr = Tg.q(f2r).gather(1, H.q(f2r).argmax(1, keepdim=True))[:, 0]
                yr = rr + R.GAMMA * (1 - dr) * tr
            qr = H.q(fr).gather(1, ar[:, None])[:, 0]
            lqr = F.smooth_l1_loss(qr, yr)
            lrw = F.mse_loss(H.r(fr).gather(1, ar[:, None])[:, 0], rr)
            dl = H.d(fr).gather(1, ar[:, None])[:, 0]
            # deaths are rare per decision: weight them so the head doesn't just say "never"
            ld = F.binary_cross_entropy_with_logits(dl, dr, pos_weight=torch.tensor(a.death_pw, device="cuda"))
            loss = lqr + lrw + ld; lqi = torch.zeros((), device="cuda")
            if imag.n >= a.warmup:
                fi, ai, f2i, _, _ = imag.sample(a.bs)
                with torch.no_grad():
                    ri = H.r(fi).gather(1, ai[:, None])[:, 0]; pi = torch.sigmoid(H.d(fi).gather(1, ai[:, None])[:, 0])
                    pi = pi / (pi + (1 - pi) * a.death_pw)              # undo the pos_weight bias -> calibrated-ish prob
                    ti = Tg.q(f2i).gather(1, H.q(f2i).argmax(1, keepdim=True))[:, 0]
                    yi = ri + R.GAMMA * (1 - pi) * ti
                lqi = F.smooth_l1_loss(H.q(fi).gather(1, ai[:, None])[:, 0], yi); loss = loss + a.imag_w * lqi
            opt.zero_grad(set_to_none=True); loss.backward()
            torch.nn.utils.clip_grad_norm_(H.parameters(), 10.0); opt.step(); step += 1
            with torch.no_grad():
                for p, q in zip(Tg.parameters(), H.parameters()): p.lerp_(q, a.tau)
                acc["lq"] += float(lqr + lqi); acc["lqr"] += float(lqr); acc["lqi"] += float(lqi); acc["lr_"] += float(lrw)
                acc["ld"] += float(ld); acc["q"] += float(qr.mean()); acc["n"] += 1
                pd = torch.sigmoid(dl)
                if dr.sum() > 0: acc["pd_dead"] += float(pd[dr > 0].mean()); acc["nd"] += 1
                acc["pd_alive"] += float(pd[dr == 0].mean())
        now = time.time()
        if now - t_save > 15 and step > 0:
            ver += 1; R.save_atomic(dict(heads=H.state_dict(), ver=ver, step=step), f"{OUT}/heads.pt")
            R.save_atomic(dict(heads=H.state_dict(), targ=Tg.state_dict(), opt=opt.state_dict(), step=step, ver=ver), f"{OUT}/learner_state.pt")
            t_save = now
        if now - t_log > 30:
            n = max(1, acc["n"])
            rec = dict(t=now, step=step, ver=ver, real_n=real.n, real_total=real.total, imag_n=imag.n, imag_total=imag.total,
                       real_eps=stats["real_eps"], deaths=stats["deaths"], steps_per_s=acc["n"] / max(1e-9, now - t_log) if t_log else 0,
                       q_loss=acc["lq"] / n, q_loss_real=acc["lqr"] / n, q_loss_imag=acc["lqi"] / n, r_loss=acc["lr_"] / n,
                       d_loss=acc["ld"] / n, q_mean=acc["q"] / n, pdeath_dead=acc["pd_dead"] / max(1, acc["nd"]),
                       pdeath_alive=acc["pd_alive"] / n, uptime_h=(now - t0) / 3600)
            with open(f"{OUT}/dash/learner.jsonl", "a") as fh: fh.write(json.dumps(rec) + "\n")
            R.jdump(rec, f"{OUT}/dash/learner.json")
            acc = {k: 0. for k in acc}; acc["n"] = 0; acc["nd"] = 0; t_log = now
        if now - t_hf > 1800:
            t_hf = now
            try:
                from huggingface_hub import HfApi
                files = [(f"{OUT}/learner_state.pt", "rl/learner_state.pt")] + [(p, f"rl/dash/{os.path.basename(p)}") for p in glob.glob(f"{OUT}/dash/*.jsonl")]
                HfApi().batch_bucket_files("mundoamundo/slither-maskgit-live", add=files)
                print(f"hf backup ok ({len(files)} files)", flush=True)
            except Exception as e: print(f"hf backup failed: {e}", flush=True)


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--bs", type=int, default=512); p.add_argument("--lr", type=float, default=3e-4)
    p.add_argument("--cap", type=int, default=3_000_000); p.add_argument("--warmup", type=int, default=5000)
    p.add_argument("--replay_ratio", type=float, default=16.0, help="times each transition is sampled on average")
    p.add_argument("--tau", type=float, default=0.005); p.add_argument("--imag_w", type=float, default=1.0)
    p.add_argument("--death_pw", type=float, default=20.0)
    main(p.parse_args())
